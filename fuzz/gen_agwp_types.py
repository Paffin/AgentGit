#!/usr/bin/env python3
"""Generates fuzz/src/agwp_types.rs: one decoder per top-level message of proto/agwp/v1/agwp.proto.

The AGWP fuzz targets (agwp_proto, agwp_json) pick a message type by index, so the list of types must follow
the protocol. Run without arguments to rewrite the file, with --check to fail when it is stale (CI does).
"""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
PROTO = ROOT / "proto" / "agwp" / "v1" / "agwp.proto"
OUT = ROOT / "fuzz" / "src" / "agwp_types.rs"


def render() -> str:
    names = re.findall(r"^message\s+(\w+)\s*\{", PROTO.read_text(), re.M)
    names = [n for n in names if n != "Empty"] + ["Empty"]
    lines = [
        "// @generated by fuzz/gen_agwp_types.py from proto/agwp/v1/agwp.proto. Do not edit.",
        "",
        "use ag_protocol::v1;",
        "",
        "/// Number of message types the decoders below cover.",
        f"pub const COUNT: usize = {len(names)};",
        "",
        "/// Name of message type `idx`.",
        "pub fn name(idx: usize) -> &'static str {",
        "    match idx % COUNT {",
    ]
    for i, n in enumerate(names):
        lines.append(f'        {i} => "{n}",')
    lines += [
        "        _ => unreachable!(),",
        "    }",
        "}",
        "",
        "/// Decodes `data` as protobuf message `idx`; whatever decodes must survive an encode/decode round trip.",
        "pub fn check_proto(idx: usize, data: &[u8]) {",
        "    use prost::Message;",
        "    match idx % COUNT {",
    ]
    for i, n in enumerate(names):
        lines.append(
            f"        {i} => if let Ok(m) = v1::{n}::decode(data) {{ \
let bytes = m.encode_to_vec(); assert_eq!(v1::{n}::decode(bytes.as_slice()).unwrap(), m); \
assert_eq!(bytes.len(), m.encoded_len()); }},"
        )
    lines += [
        "        _ => unreachable!(),",
        "    }",
        "}",
        "",
        "/// Decodes `data` as the JSON form of message `idx`; whatever decodes must serialise and decode to itself.",
        "pub fn check_json(idx: usize, data: &[u8]) {",
        "    match idx % COUNT {",
    ]
    for i, n in enumerate(names):
        lines.append(
            f"        {i} => if let Ok(m) = serde_json::from_slice::<v1::{n}>(data) {{ \
let s = serde_json::to_string(&m).unwrap(); \
assert_eq!(serde_json::from_str::<v1::{n}>(&s).unwrap(), m); }},"
        )
    lines += ["        _ => unreachable!(),", "    }", "}", ""]
    return "\n".join(lines)


def main() -> int:
    text = render()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text() != text:
            print(f"{OUT.relative_to(ROOT)} is stale: run python3 fuzz/gen_agwp_types.py", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
