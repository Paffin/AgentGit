#!/usr/bin/env python3
"""Keeps fuzz/Cargo.toml's [[bin]] list in step with fuzz/fuzz_targets/*.rs.

cargo-fuzz needs one [[bin]] per target. Targets whose crates pull in a large dependency tree (SQLite, PostgreSQL,
the gRPC stack) are `required-features = ["heavy"]` so that the light ones - the format decoders, diff, merge,
policy - build in a minute and a few hundred MB. CI builds both sets (`--features heavy`).

  fuzz/sync_targets.py          rewrite the [[bin]] section
  fuzz/sync_targets.py --check  exit 1 if it is out of date (CI runs this)
"""
import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent
HEAVY = {"agwp_json", "agwp_proto", "git_parse", "ignore_rules", "job_spec", "signed_json"}
MARK = "# --- targets (generated by fuzz/sync_targets.py) ---"


def render() -> str:
    head = (HERE / "Cargo.toml").read_text().split(MARK)[0].rstrip() + "\n\n" + MARK + "\n"
    for t in sorted(p.stem for p in (HERE / "fuzz_targets").glob("*.rs")):
        head += f'\n[[bin]]\nname = "{t}"\npath = "fuzz_targets/{t}.rs"\ntest = false\ndoc = false\nbench = false\n'
        if t in HEAVY:
            head += 'required-features = ["heavy"]\n'
    return head


def main() -> int:
    text = render()
    path = HERE / "Cargo.toml"
    if "--check" in sys.argv:
        if path.read_text() != text:
            print("fuzz/Cargo.toml is out of date: run python3 fuzz/sync_targets.py", file=sys.stderr)
            return 1
        return 0
    path.write_text(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
