#!/usr/bin/env python3
"""Renders deploy/observability/alerts.yml as a PrometheusRule for the Prometheus Operator.

    python3 scripts/gen_prometheusrule.py           # rewrite the overlay file
    python3 scripts/gen_prometheusrule.py --check   # fail if it is out of date (CI)

alerts.yml is the single source of truth; the overlay file is generated from it.
"""
import pathlib
import sys

import yaml

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "deploy/observability/alerts.yml"
DST = ROOT / "deploy/kubernetes/overlays/prometheus-operator/prometheusrule.yaml"

HEADER = "# Generated by scripts/gen_prometheusrule.py from deploy/observability/alerts.yml. Do not edit.\n"


def render() -> str:
    groups = yaml.safe_load(SRC.read_text())["groups"]
    doc = {
        "apiVersion": "monitoring.coreos.com/v1",
        "kind": "PrometheusRule",
        "metadata": {"name": "ag-server", "labels": {"app.kubernetes.io/part-of": "agentgit"}},
        "spec": {"groups": groups},
    }
    return HEADER + yaml.safe_dump(doc, sort_keys=False, width=100)


def main() -> int:
    text = render()
    if "--check" in sys.argv:
        if not DST.exists() or DST.read_text() != text:
            print(f"{DST.relative_to(ROOT)} is out of date; run scripts/gen_prometheusrule.py", file=sys.stderr)
            return 1
        return 0
    DST.write_text(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
