def class_name(ns: str) -> str:
    return "".join(p.capitalize() for p in ns.split("_")) + "Api"


def method_py(o: Op, is_async: bool) -> str:
    kw = "async def" if is_async else "def"
    aw = "await " if is_async else ""
    required = [p for p in o.params if p.required]
    optional = [p for p in o.params if not p.required]
    sig = ["self", "*"]
    for p in required:
        sig.append(f"{p.name}: {p.typ}")
    for p in optional:
        sig.append(f"{p.name}: {p.typ} | None = None")
    sig.append("options: CallOptions | None = None")
    if o.id == "events.subscribe":
        return ""
    ret = o.result
    wire = ", ".join(f"{json.dumps(p.wire)}: {p.name}" for p in o.params)
    lines = [f"    {kw} {o.name}(\n"]
    for s in sig:
        lines.append(f"        {s},\n" if s not in ("self", "*") else f"        {s},\n")
    lines.append(f"    ) -> {ret}:\n")
    summary = o.summary or o.id
    lines.append(doc(f"{summary} (`{o.http} {o.route}`, operation `{o.id}`).", "        "))
    if o.id == "objects.put":
        lines.append(
            f"        return {aw}self._c._call_put(repo=repo, object_id=object_id, data=data, options=options)\n"
        )
    else:
        lines.append(f"        return {aw}self._c._call({json.dumps(o.id)}, {{{wire}}}, options, {ret})\n")
    lines.append("\n")
    return "".join(lines)


def events_methods(is_async: bool) -> str:
    kw_ret = "AsyncGenerator[Event, None]" if is_async else "Generator[Event, None, None]"
    return (
        "    def subscribe(\n"
        "        self,\n"
        "        *,\n"
        "        repo: str,\n"
        "        after_seq: int | None = None,\n"
        "        topics: Sequence[str] | None = None,\n"
        "        heartbeat_ms: int | None = None,\n"
        "        idle_timeout_ms: int | None = None,\n"
        "        reconnect: ReconnectPolicy | None = None,\n"
        "        run_id: str | None = None,\n"
        f"    ) -> {kw_ret}:\n"
        '        """Server-Sent Events: replay after `after_seq`, then follow live, reconnecting and resuming '
        '(`GET /v1/repos/{owner}/{rname}/events`, operation `events.subscribe`)."""\n'
        "        return self._c._subscribe(\n"
        "            repo=repo,\n"
        "            after_seq=after_seq,\n"
        "            topics=topics,\n"
        "            heartbeat_ms=heartbeat_ms,\n"
        "            idle_timeout_ms=idle_timeout_ms,\n"
        "            reconnect=reconnect,\n"
        "            run_id=run_id,\n"
        "        )\n\n"
    )


def namespaces_py(ops: list[Op]) -> str:
    out = [BANNER, "from __future__ import annotations\n\n"]
    out.append("from collections.abc import AsyncGenerator, Generator, Mapping, Sequence\n")
    out.append("from typing import Any\n\n")
    out.append("from agentgit._generated.models import (\n")
    for name in sorted(SCHEMAS) + ["PutObjectResult"]:
        out.append(f"    {name},\n")
    out.append(")\n")
    out.append("from agentgit._options import CallOptions, ReconnectPolicy\n")
    out.append("from agentgit._protocols import AsyncCaller, SyncCaller\n\n")
    by_ns: dict[str, list[Op]] = {}
    for o in ops:
        by_ns.setdefault(o.namespace, []).append(o)
    for is_async in (False, True):
        prefix = "Async" if is_async else ""
        caller = "AsyncCaller" if is_async else "SyncCaller"
        for ns in sorted(by_ns):
            cname = prefix + class_name(ns)
            out.append(f"\nclass {cname}:\n")
            out.append(f'    """The `{ns}` operations."""\n\n')
            out.append('    __slots__ = ("_c",)\n\n')
            out.append(f"    def __init__(self, caller: {caller}) -> None:\n")
            out.append("        self._c = caller\n\n")
            for o in sorted(by_ns[ns], key=lambda x: x.name):
                if o.id == "events.subscribe":
                    out.append(events_methods(is_async))
                else:
                    out.append(method_py(o, is_async))
            out.append("\n")
    return "".join(out).rstrip("\n") + "\n"


def main() -> None:
    ops = build_ops()
    files = {
        "models.py": models_py(),
        "operations.py": operations_py(ops),
        "namespaces.py": namespaces_py(ops),
    }
    stale = 0
    for name, text in files.items():
        path = OUT / name
        if "--check" in sys.argv:
            if not path.exists() or path.read_text() != text:
                print(f"stale: src/agentgit/_generated/{name}", file=sys.stderr)
                stale += 1
        else:
            OUT.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
            print(f"wrote src/agentgit/_generated/{name}")
    if "--check" in sys.argv:
        if stale:
            print(
                "Generated files are out of date; run `python scripts/generate.py` and commit the result.",
                file=sys.stderr,
            )
            sys.exit(1)
        print(f"generated files are up to date ({len(ops)} operations)")
    else:
        print(f"{len(ops)} operations")


if __name__ == "__main__":
    main()
