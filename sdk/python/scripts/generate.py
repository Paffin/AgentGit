#!/usr/bin/env python3
"""Generates src/agentgit/_generated/ from docs/protocol/openapi.json and sdk/api-policy.json.

    python scripts/generate.py            rewrite the files
    python scripts/generate.py --check    exit 1 if the checked-in files are stale (CI)

models.py       one dataclass per message of the OpenAPI document
operations.py   the route table (one entry per operation id) and the paginated-operation map
namespaces.py   the synchronous and asynchronous namespace classes, one method per operation id
"""

from __future__ import annotations

import json
import keyword
import sys
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parent.parent
SPEC = json.loads((ROOT / "../../docs/protocol/openapi.json").read_text())
POLICY = json.loads((ROOT / "../api-policy.json").read_text())
OUT = ROOT / "src/agentgit/_generated"

BANNER = (
    "# GENERATED by scripts/generate.py from docs/protocol/openapi.json - do not edit.\n"
    "# Regenerate with `python scripts/generate.py`; CI runs it with --check.\n"
)
SCHEMAS: dict[str, Any] = SPEC["components"]["schemas"]
ALWAYS_PRESENT = set(POLICY["alwaysPresent"]["fields"])


def ref_name(schema: dict[str, Any] | None) -> str | None:
    if schema and "$ref" in schema:
        return str(schema["$ref"]).rsplit("/", 1)[-1]
    return None


def py_name(name: str) -> str:
    return name + "_" if keyword.iskeyword(name) else name


def doc(text: str, indent: str) -> str:
    text = " ".join(str(text).split()).replace("\\", "\\\\").replace('"""', '\\"\\"\\"')
    if not text:
        return ""
    if text.endswith('"'):
        text += " "
    return f'{indent}"""{text}"""\n'


