# models
# --------------------------------------------------------------------------------------------


def optional_ref(prop: dict[str, Any]) -> str | None:
    """`oneOf: [{$ref}, {type: null}]` -> the referenced name."""
    for alt in prop.get("oneOf", []):
        if "$ref" in alt:
            return ref_name(alt)
    return None


def scalar_type(prop: dict[str, Any]) -> str | None:
    """The JSON type of a property; `["string", "null"]` (a nullable scalar) is `"string"`."""
    t = prop.get("type")
    if isinstance(t, list):
        present = [x for x in t if x != "null"]
        return str(present[0]) if len(present) == 1 else None
    return str(t) if t is not None else None


def is_string_enum(schema: dict[str, Any]) -> bool:
    """A schema that is a closed set of strings (`LoginToken`), not a message."""
    return schema.get("type") == "string" and isinstance(schema.get("enum"), list)


def model_type(prop: dict[str, Any]) -> str:
    """The Python type of a response/message field."""
    name = ref_name(prop) or optional_ref(prop)
    if name:
        return name
    t = scalar_type(prop)
    if t == "string":
        return "str"
    if t == "integer":
        return "int"
    if t == "number":
        return "float"
    if t == "boolean":
        return "bool"
    if t == "array":
        return f"list[{model_type(prop['items'])}]"
    if t == "object":
        add = prop.get("additionalProperties")
        if isinstance(add, dict) and add.get("type") == "string":
            return "dict[str, str]"
        return "dict[str, Any]"
    return "Any"


def input_type(prop: dict[str, Any]) -> str:
    """The type accepted for a request parameter (dataclass instances or plain mappings)."""
    name = ref_name(prop) or optional_ref(prop)
    if name and is_string_enum(SCHEMAS[name]):
        return name
    if name:
        return f"{name} | Mapping[str, Any]"
    t = prop.get("type")
    if t == "array":
        inner = input_type(prop["items"])
        return f"Sequence[{inner}]"
    if t == "object":
        add = prop.get("additionalProperties")
        if isinstance(add, dict) and add.get("type") == "string":
            return "Mapping[str, str]"
        return "Mapping[str, Any]"
    return model_type(prop)


def model_field(schema_name: str, wire: str, prop: dict[str, Any]) -> str:
    name = py_name(wire)
    typ = model_type(prop)
    ref = ref_name(prop) or optional_ref(prop)
    meta = f', metadata={{"wire": "{wire}"}}' if name != wire else ""
    if ref:
        if f"{schema_name}.{wire}" in ALWAYS_PRESENT:
            return f"    {name}: {typ} = field(default_factory=lambda: {ref}(){meta})\n"
        return f"    {name}: {typ} | None = field(default=None{meta})\n"
    default = prop.get("default", None)
    t = prop.get("type")
    if t in ("array", "object"):
        factory = "list" if t == "array" else "dict"
        return f"    {name}: {typ} = field(default_factory={factory}{meta})\n"
    if t == "string":
        text = default if isinstance(default, str) else ""
        return f"    {name}: {typ} = field(default={json.dumps(text)}{meta})\n"
    if t in ("integer", "number"):
        return f"    {name}: {typ} = field(default={default if default is not None else 0}{meta})\n"
    if t == "boolean":
        return f"    {name}: {typ} = field(default={bool(default)}{meta})\n"
    return f"    {name}: {typ} | None = field(default=None{meta})\n"


def models_py() -> str:
    out = [BANNER, "from __future__ import annotations\n\n", "from dataclasses import dataclass, field\n"]
    out.append("from typing import Any, Literal\n\n")
    names = sorted(SCHEMAS)
    out.append(f"__all__ = {json.dumps(names + ['PutObjectResult'], indent=4)}\n\n\n")
    for name in names:
        schema = SCHEMAS[name]
        if is_string_enum(schema):
            # on the wire it is one of these strings: a type alias, not a class
            out.append(f"# {' '.join(str(schema.get('description', name)).split())}\n")
            out.append(f"{name} = Literal[{', '.join(json.dumps(v) for v in schema['enum'])}]\n\n\n")
            continue
        out.append("@dataclass(kw_only=True)\n")
        out.append(f"class {name}:\n")
        out.append(doc(schema.get("description", f"The `{name}` message."), "    "))
        props = schema.get("properties", {})
        if not props:
            out.append("    pass\n")
        for wire in sorted(props):
            prop = props[wire]
            out.append(model_field(name, wire, prop))
        out.append("\n\n")
    out.append(
        "@dataclass(kw_only=True)\n"
        "class PutObjectResult:\n"
        '    """What `PUT /objects/{id}` answers (not described by the OpenAPI document)."""\n'
        '    object_id: str = field(default="")\n'
        "    stored: bool = field(default=False)\n"
    )
    return "".join(out).rstrip("\n") + "\n"


