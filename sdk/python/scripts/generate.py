def place_of(op_id: str) -> tuple[str, str]:
    parts = op_id.split(".")
    for prefix in (".".join(parts[:2]), parts[0]):
        ns = POLICY["namespaces"].get(prefix)
        if ns is not None and op_id.startswith(prefix + "."):
            return ns, op_id[len(prefix) + 1 :].replace(".", "_")
    raise SystemExit(f"no namespace configured for operation {op_id!r}")


def classify(op_id: str, http: str) -> str:
    r = POLICY["retry"]
    if op_id in r["keyed"]:
        return "keyed"
    if http == "GET" or op_id in r["readPosts"]:
        return "read"
    if op_id in r["natural"]:
        return "natural"
    return "unsafe"


@dataclass
class Param:
    name: str  # python name
    wire: str
    typ: str  # input type
    required: bool
    doc: str = ""


@dataclass
class Op:
    id: str
    http: str
    route: str
    namespace: str
    name: str
    summary: str
    path_params: list[str]
    query_params: list[str]
    body: str
    response: str
    retry: str
    retry_when_field: str | None
    idempotency_key: bool
    public: bool
    items_key: str | None
    result: str  # python result type
    params: list[Param] = field(default_factory=list)


def content_kind(content: dict[str, Any] | None) -> str | None:
    """What an OpenAPI ``content`` map carries: JSON, raw bytes, or a Server-Sent Events stream."""
    if not content:
        return None
    if "application/json" in content:
        return "json"
    if "text/event-stream" in content:
        return "sse"
    if "application/octet-stream" in content:
        return "bytes"
    raise SystemExit(f"unsupported media types: {', '.join(content)}")


def build_ops() -> list[Op]:
    ops: list[Op] = []
    for route, item in SPEC["paths"].items():
        for verb, o in item.items():
            op_id = o["operationId"]
            http = verb.upper()
            parameters = o.get("parameters", [])
            bodies = POLICY["bodies"].get(op_id, {})
            req_name = ref_name(
                o.get("requestBody", {}).get("content", {}).get("application/json", {}).get("schema")
            )
            res_name = ref_name(
                o["responses"]["200"].get("content", {}).get("application/json", {}).get("schema")
            )
            req_schema = SCHEMAS.get(req_name or "", {})
            res_schema = SCHEMAS.get(res_name or "", {})
            arrays = [k for k, v in res_schema.get("properties", {}).items() if v.get("type") == "array"]
            paginated = (
                arrays[0]
                if res_schema and "next_page_token" in res_schema.get("properties", {}) and len(arrays) == 1
                else None
            )
            ns, name = place_of(op_id)
            body = bodies.get("request") or content_kind(o.get("requestBody", {}).get("content")) or "none"
            response = bodies.get("response") or content_kind(o["responses"]["200"].get("content")) or "json"
            path_params = [p["name"] for p in parameters if p["in"] == "path"]
            repo_scoped = "owner" in path_params and "rname" in path_params
            params: list[Param] = []
            if repo_scoped:
                params.append(Param("repo", "repo", "str", True, "Repository, as `owner/name`."))
            for p in path_params:
                if p in ("owner", "rname"):
                    continue
                params.append(Param(py_name(p), p, "str", True))
            used = {p.wire for p in params}
            if body == "json":
                for wire, prop in sorted(req_schema.get("properties", {}).items()):
                    if wire in used:
                        continue
                    params.append(
                        Param(py_name(wire), wire, input_type(prop), False, prop.get("description", ""))
                    )
            elif body in ("none", "bytes"):
                for p in parameters:
                    if p["in"] != "query" or p["name"] in used:
                        continue
                    params.append(
                        Param(
                            py_name(p["name"]),
                            p["name"],
                            input_type(p["schema"]),
                            False,
                            p.get("description", ""),
                        )
                    )
            if body == "bytes":
                params.append(Param("data", "data", "bytes", True, "The binary request body."))
            if op_id == "events.subscribe":
                params = []
            result = res_name or "Any"
            if response == "bytes":
                result = "bytes"
            if op_id == "objects.put":
                result = "PutObjectResult"
            ops.append(
                Op(
                    id=op_id,
                    http=http,
                    route=route,
                    namespace=ns,
                    name=name,
                    summary=" ".join(o.get("summary", "").split()),
                    path_params=path_params,
                    query_params=[p["name"] for p in parameters if p["in"] == "query"],
                    body=body,
                    response=response,
                    retry=classify(op_id, http),
                    retry_when_field=POLICY["retry"]["naturalWhenFieldPresent"].get(op_id),
                    idempotency_key="idempotency_key" in req_schema.get("properties", {})
                    or op_id in POLICY["retry"]["keyed"],
                    public=isinstance(o.get("security"), list) and len(o["security"]) == 0,
                    items_key=paginated,
                    result=result,
                    params=params,
                )
            )
    ops.sort(key=lambda x: x.id)
    seen: dict[str, str] = {}
    for o in ops:
        key = f"{o.namespace}.{o.name}"
        if key in seen:
            raise SystemExit(f"{o.id} and {seen[key]} both map to {key}")
        seen[key] = o.id
    check_hand_written_operations(ops)
    return ops


def check_hand_written_operations(ops: list[Op]) -> None:
    """The operations that are not plain JSON have hand-written methods; the document must keep matching them."""
    non_json = {o.id for o in ops if o.body not in ("json", "none") or o.response != "json"}
    hand_written = {"objects.put", "objects.get", "tree.file", "events.subscribe", "migration.prepare"}
    if non_json != hand_written:
        raise SystemExit(
            f"non-JSON operations in the document: {sorted(non_json)}, expected {sorted(hand_written)}"
        )
    expected_query = {
        "migration.prepare": {"name"},
        "objects.put": set(),
        "objects.get": set(),
        "tree.file": {"rev"},
        "events.subscribe": {"after_seq", "heartbeat_ms", "topics"},
    }
    for o in ops:
        if o.id in expected_query and set(o.query_params) != expected_query[o.id]:
            raise SystemExit(f"{o.id}: the document lists query parameters {o.query_params}")


def operations_py(ops: list[Op]) -> str:
    out = [
        BANNER,
        "from __future__ import annotations\n\n",
        "from agentgit._operation import OperationInfo\n\n",
    ]
    out.append("OPERATIONS: dict[str, OperationInfo] = {\n")
    for o in ops:
        out.append(f"    {json.dumps(o.id)}: OperationInfo(\n")
        out.append(f"        id={json.dumps(o.id)},\n")
        out.append(f"        http={json.dumps(o.http)},\n")
        out.append(f"        route={json.dumps(o.route)},\n")
        out.append(f"        namespace={json.dumps(o.namespace)},\n")
        out.append(f"        name={json.dumps(o.name)},\n")
        out.append(f"        summary={json.dumps(o.summary)},\n")
        out.append(f"        path_params={tuple(o.path_params)!r},\n")
        out.append(f"        query_params={tuple(o.query_params)!r},\n")
        out.append(f"        body={json.dumps(o.body)},\n")
        out.append(f"        response={json.dumps(o.response)},\n")
        out.append(f"        retry={json.dumps(o.retry)},\n")
        if o.retry_when_field:
            out.append(f"        retry_when_field={json.dumps(o.retry_when_field)},\n")
        out.append(f"        idempotency_key={o.idempotency_key},\n")
        out.append(f"        public={o.public},\n")
        out.append("    ),\n")
    out.append("}\n\n")
    out.append(
        "# Operations whose response carries `next_page_token`, and the list property holding the items.\n"
    )
    out.append("PAGINATED: dict[str, str] = {\n")
    for o in ops:
        if o.items_key:
            out.append(f"    {json.dumps(o.id)}: {json.dumps(o.items_key)},\n")
    out.append("}\n\n")
    out.append("# namespace -> method -> operation id\n")
    out.append("NAMESPACE_METHODS: dict[str, dict[str, str]] = {\n")
    by_ns: dict[str, list[Op]] = {}
    for o in ops:
        by_ns.setdefault(o.namespace, []).append(o)
    for ns in sorted(by_ns):
        out.append(f"    {json.dumps(ns)}: {{\n")
        for o in sorted(by_ns[ns], key=lambda x: x.name):
            out.append(f"        {json.dumps(o.name)}: {json.dumps(o.id)},\n")
        out.append("    },\n")
    out.append("}\n")
    return "".join(out)


