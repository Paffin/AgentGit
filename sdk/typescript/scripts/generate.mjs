#!/usr/bin/env node
// Generates everything in src/generated/ from docs/protocol/openapi.json (+ sdk/api-policy.json):
//
//   schema.ts      the message types, by openapi-typescript
//   models.ts      one exported type alias per message
//   operations.ts  the operation table and the paginated-operation map
//   api.ts         the typed namespaces interface (one method per operation id)
//
//   node scripts/generate.mjs           rewrite the files
//   node scripts/generate.mjs --check   exit 1 if the checked-in files are stale (CI)

import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import openapiTS, { astToString } from 'openapi-typescript';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '..');
const specPath = path.resolve(root, '../../docs/protocol/openapi.json');
const policyPath = path.resolve(root, '../api-policy.json');
const outDir = path.resolve(root, 'src/generated');
const check = process.argv.includes('--check');

const spec = JSON.parse(readFileSync(specPath, 'utf8'));
const policy = JSON.parse(readFileSync(policyPath, 'utf8'));

const BANNER =
  '// GENERATED by scripts/generate.mjs from docs/protocol/openapi.json - do not edit.\n' +
  '// Regenerate with `npm run generate`; CI runs `npm run generate:check`.\n';

const camel = (s) => s.replace(/_([a-z0-9])/g, (_, c) => c.toUpperCase());
const refName = (schema) => (schema?.$ref ? schema.$ref.split('/').pop() : undefined);
const quote = (s) => `'${String(s).replaceAll('\\', '\\\\').replaceAll("'", "\\'")}'`;
const list = (a) => `[${a.map(quote).join(', ')}]`;

/** operation id -> { namespace, snake, name } (longest configured prefix wins). */
function placeOf(id) {
  const parts = id.split('.');
  for (const prefix of [parts.slice(0, 2).join('.'), parts[0]]) {
    const ns = policy.namespaces[prefix];
    if (ns !== undefined && id.startsWith(prefix + '.')) {
      const snake = id.slice(prefix.length + 1).replaceAll('.', '_');
      return { namespace: ns, snake, name: camel(snake) };
    }
  }
  throw new Error(`no namespace configured for operation '${id}' (sdk/api-policy.json)`);
}

function classify(id, http) {
  const r = policy.retry;
  if (r.keyed.includes(id)) return 'keyed';
  if (http === 'GET' || r.readPosts.includes(id)) return 'read';
  if (r.natural.includes(id)) return 'natural';
  return 'unsafe'; // including the operations that are 'natural' only when a guard field is present
}

/** What an OpenAPI `content` map carries: JSON, raw bytes, or a Server-Sent Events stream. */
function contentKind(content) {
  if (!content || Object.keys(content).length === 0) return undefined;
  if ('application/json' in content) return 'json';
  if ('text/event-stream' in content) return 'sse';
  if ('application/octet-stream' in content) return 'bytes';
  throw new Error(`unsupported media types: ${Object.keys(content).join(', ')}`);
}

const ops = [];
for (const [route, item] of Object.entries(spec.paths)) {
  for (const [verb, op] of Object.entries(item)) {
    const id = op.operationId;
    const http = verb.toUpperCase();
    const params = op.parameters ?? [];
    const bodies = policy.bodies[id] ?? {};
    const reqName = refName(op.requestBody?.content?.['application/json']?.schema);
    const resName = refName(op.responses?.['200']?.content?.['application/json']?.schema);
    const reqSchema = reqName ? spec.components.schemas[reqName] : undefined;
    const resSchema = resName ? spec.components.schemas[resName] : undefined;
    const arrays = Object.entries(resSchema?.properties ?? {}).filter(([, v]) => v.type === 'array');
    const paginated =
      resSchema && 'next_page_token' in (resSchema.properties ?? {}) && arrays.length === 1 ? arrays[0][0] : undefined;
    ops.push({
      id,
      http,
      route,
      ...placeOf(id),
      summary: (op.summary ?? '').replace(/\s+/g, ' ').trim(),
      pathParams: params.filter((p) => p.in === 'path').map((p) => p.name),
      queryParams: params.filter((p) => p.in === 'query').map((p) => p.name),
      body: bodies.request ?? contentKind(op.requestBody?.content) ?? 'none',
      response: bodies.response ?? contentKind(op.responses?.['200']?.content) ?? 'json',
      retry: classify(id, http),
      retryWhenField: policy.retry.naturalWhenFieldPresent[id],
      idempotencyKey: Boolean(reqSchema?.properties && 'idempotency_key' in reqSchema.properties),
      public: Array.isArray(op.security) && op.security.length === 0,
      paginated,
    });
  }
}
ops.sort((a, b) => a.id.localeCompare(b.id));

const taken = new Map();
for (const o of ops) {
  const key = `${o.namespace}.${o.name}`;
  if (taken.has(key)) throw new Error(`${o.id} and ${taken.get(key)} both map to ${key}`);
  taken.set(key, o.id);
}

function operationsTs() {
  const out = [BANNER, "import type { OperationInfo } from '../operation.js';", ''];
  out.push('/** Every route of the HTTP/JSON API, keyed by OpenAPI operation id. */');
  out.push('export const OPERATIONS = {');
  for (const o of ops) {
    out.push(`  ${quote(o.id)}: {`);
    out.push(`    id: ${quote(o.id)},`);
    out.push(`    http: ${quote(o.http)},`);
    out.push(`    route: ${quote(o.route)},`);
    out.push(`    namespace: ${quote(o.namespace)},`);
    out.push(`    name: ${quote(o.name)},`);
    out.push(`    summary: ${quote(o.summary)},`);
    out.push(`    pathParams: ${list(o.pathParams)},`);
    out.push(`    queryParams: ${list(o.queryParams)},`);
    out.push(`    body: ${quote(o.body)},`);
    out.push(`    response: ${quote(o.response)},`);
    out.push(`    retry: ${quote(o.retry)},`);
    if (o.retryWhenField) out.push(`    retryWhenField: ${quote(o.retryWhenField)},`);
    out.push(`    idempotencyKey: ${o.idempotencyKey},`);
    out.push(`    public: ${o.public},`);
    out.push('  },');
  }
  out.push('} as const satisfies Record<string, OperationInfo>;', '');
  out.push('export type OperationId = keyof typeof OPERATIONS;', '');
  out.push('/** Operations whose response carries `next_page_token`, and the array property holding the items. */');
  out.push('export const PAGINATED = {');
  for (const o of ops.filter((x) => x.paginated)) out.push(`  ${quote(o.id)}: ${quote(o.paginated)},`);
  out.push('} as const;', '');
  out.push('export type PaginatedOperationId = keyof typeof PAGINATED;', '');
  return out.join('\n');
}

/** Hand-typed signatures for the operations whose body or response is not JSON. */
const SPECIAL = {
  'objects.put':
    '(request: { repo: string; object_id: string; data: Uint8Array }, options?: CallOptions): Promise<PutObjectResult>',
  'objects.get': '(request: { repo: string; object_id: string }, options?: CallOptions): Promise<Uint8Array>',
  'tree.file': '(request: { repo: string; path: string; rev?: string }, options?: CallOptions): Promise<Uint8Array>',
  'events.subscribe': '(options: SubscribeEventsOptions): AsyncGenerator<AgentEvent, void, undefined>',
};

// The hand-typed signatures above must keep matching the document: the same operations are non-JSON, and
// they take the query parameters the signatures name.
{
  const nonJson = ops.filter((o) => o.body !== 'json' && o.body !== 'none').map((o) => o.id);
  nonJson.push(...ops.filter((o) => o.response !== 'json').map((o) => o.id));
  const expected = {
    'objects.put': [],
    'objects.get': [],
    'tree.file': ['rev'],
    'events.subscribe': ['after_seq', 'heartbeat_ms', 'topics'],
  };
  const same = (a, b) => JSON.stringify([...a].sort()) === JSON.stringify([...b].sort());
  if (!same(new Set(nonJson), Object.keys(SPECIAL))) {
    throw new Error(
      `non-JSON operations in the document: ${[...new Set(nonJson)].sort()}; SPECIAL has ${Object.keys(SPECIAL)}`,
    );
  }
  for (const [id, query] of Object.entries(expected)) {
    const got = ops.find((o) => o.id === id)?.queryParams ?? [];
    if (!same(got, query))
      throw new Error(`${id}: the document lists query parameters [${got}], the signature has [${query}]`);
  }
}

function apiTs() {
  const out = [BANNER];
  out.push("import type { OperationId } from './operations.js';");
  out.push(
    "import type { AgentEvent, CallOptions, PutObjectResult, Req, Res, SubscribeEventsOptions } from '../types.js';",
  );
  out.push('');
  out.push('/** The operation behind each namespaced method, for tooling and tests. */');
  out.push('export const NAMESPACE_METHODS = {');
  const byNs = new Map();
  for (const o of ops) {
    if (!byNs.has(o.namespace)) byNs.set(o.namespace, []);
    byNs.get(o.namespace).push(o);
  }
  const namespaces = [...byNs.keys()].sort();
  for (const ns of namespaces) {
    out.push(`  ${ns}: {`);
    for (const o of byNs.get(ns).sort((a, b) => a.name.localeCompare(b.name))) {
      out.push(`    ${o.name}: ${quote(o.id)},`);
    }
    out.push('  },');
  }
  out.push('} as const satisfies Record<string, Record<string, OperationId>>;', '');
  out.push('/** The namespaced methods of `AgentGitClient`: one per OpenAPI operation id. */');
  out.push('export interface Api {');
  for (const ns of namespaces) {
    out.push(`  readonly ${ns}: {`);
    for (const o of byNs.get(ns).sort((a, b) => a.name.localeCompare(b.name))) {
      out.push(`    /** ${o.summary.replaceAll('*/', '* /')} (\`${o.http} ${o.route}\`, operation \`${o.id}\`) */`);
      if (SPECIAL[o.id]) {
        out.push(`    ${o.name}${SPECIAL[o.id]};`);
      } else {
        const optional = o.http === 'GET' && o.pathParams.length === 0;
        const arg = `request${optional ? '?' : ''}: Req<${quote(o.id)}>`;
        out.push(`    ${o.name}(${arg}, options?: CallOptions): Promise<Res<${quote(o.id)}>>;`);
      }
    }
    out.push('  };');
  }
  out.push('}', '');
  return out.join('\n');
}

/**
 * The OpenAPI document describes free-form JSON properties (event payloads, audit details) as bare
 * `type: object`, which openapi-typescript renders as `Record<string, never>`. Widen them to open maps.
 */
function withOpenObjects(doc) {
  const copy = JSON.parse(JSON.stringify(doc));
  for (const schema of Object.values(copy.components?.schemas ?? {})) {
    for (const prop of Object.values(schema.properties ?? {})) {
      if (prop.type === 'object' && !prop.properties && !prop.additionalProperties) {
        prop.additionalProperties = true;
        prop.default = {};
      }
    }
  }
  // Fields the protocol makes optional but the server always sets (sdk/api-policy.json): not nullable.
  for (const field of policy.alwaysPresent.fields) {
    const [schemaName, prop] = field.split('.');
    const target = copy.components.schemas[schemaName]?.properties?.[prop];
    const ref = target?.oneOf?.find((x) => x.$ref)?.$ref;
    if (!ref) throw new Error(`alwaysPresent: ${field} is not an optional message field`);
    delete target.oneOf;
    target.default = {};
    target.$ref = ref;
  }
  return copy;
}

async function schemaTs() {
  const ast = await openapiTS(withOpenObjects(spec));
  return BANNER + astToString(ast);
}

/** `export type Proposal = components['schemas']['Proposal']` for every message. */
function modelsTs() {
  const out = [BANNER, "import type { components } from './schema.js';", ''];
  out.push("type S = components['schemas'];", '');
  // `Event` would shadow the DOM global of the same name; it is exported as `AgentEvent` (types.ts).
  for (const name of Object.keys(spec.components.schemas).sort()) {
    if (name === 'Event') continue;
    out.push(`export type ${name} = S[${quote(name)}];`);
  }
  out.push('');
  return out.join('\n');
}

const files = {
  'schema.ts': await schemaTs(),
  'models.ts': modelsTs(),
  'operations.ts': operationsTs(),
  'api.ts': apiTs(),
};

let stale = 0;
for (const [name, text] of Object.entries(files)) {
  const file = path.join(outDir, name);
  if (check) {
    if (!existsSync(file) || readFileSync(file, 'utf8') !== text) {
      console.error(`stale: src/generated/${name}`);
      stale++;
    }
  } else {
    mkdirSync(outDir, { recursive: true });
    writeFileSync(file, text);
    console.log(`wrote src/generated/${name}`);
  }
}
if (check) {
  if (stale > 0) {
    console.error('Generated files are out of date; run `npm run generate` and commit the result.');
    process.exit(1);
  }
  console.log(`generated files are up to date (${ops.length} operations)`);
} else {
  console.log(`${ops.length} operations`);
}
